"""プログラミングとは何か — 順次・分岐・繰り返しのデモ。

カフェの「アメリカーノ注文処理」業務マニュアルを Python の手順に置き換えてみます。
[1] 順次: 上から下へ順番に実行
[2] 分岐: 条件 (ポイント会員かどうか) によって違う道へ
[3] 繰り返し: 複数の注文を同じ手順で処理
すべてのプログラムはこの3つの組み合わせであることを、目で確かめます。
"""


def main():
    print("=" * 52)
    print(" プログラミングとは? — アメリカーノ注文処理のデモ")
    print("=" * 52)

    # ---------------------------------------------------------
    # [1] 順次 (sequence): コードは上から下へ順番に実行される
    # ---------------------------------------------------------
    print("\n[1] 順次 — 注文1件を手順どおりに処理します")

    customer = "田中さん"      # データ: お客様の名前
    cup_price = 4500           # データ: アメリカーノ1杯の価格 (ウォン)
    quantity = 2               # データ: 注文数

    print(f"  ステップ 1) 注文受付: {customer}、アメリカーノ {quantity}杯")

    total = cup_price * quantity          # 手順: 金額計算
    print(f"  ステップ 2) 金額計算: {cup_price}ウォン x {quantity}杯 = {total}ウォン")

    print(f"  ステップ 3) レシート出力: 合計 {total}ウォン 決済完了")
    print("  -> 上の3行は必ずこの順序で実行されます。これが「順次」です。")

    # ---------------------------------------------------------
    # [2] 分岐 (branch): 条件によって違う道を進む
    # ---------------------------------------------------------
    print("\n[2] 分岐 — ポイント会員かどうかで手順が分かれます")

    is_member = True           # データ: ポイント会員か? (True/False に変えてみましょう)

    if is_member:              # <-- ここが分かれ道です
        point = int(total * 0.05)   # 会員なら 5% 付与
        print(f"  会員確認 O -> ポイント {point}pt 付与")
    else:
        print("  会員確認 X -> 付与なしで次のステップへ")
    print("  -> 「もし〜ならば」で分かれるのが「分岐」です。")

    # ---------------------------------------------------------
    # [3] 繰り返し (loop): 同じ手順を複数のデータに適用する
    # ---------------------------------------------------------
    print("\n[3] 繰り返し — 待機中の注文3件を同じ手順で処理します")

    # (名前, 数量) の組が3つ入った注文待ちリスト
    waiting_orders = [
        ("佐藤さん", 1),
        ("鈴木さん", 3),
        ("高橋さん", 2),
    ]

    order_no = 0
    day_total = 0
    for name, qty in waiting_orders:      # <-- リストの各注文ごとに下の手順を繰り返す
        order_no = order_no + 1
        amount = cup_price * qty
        day_total = day_total + amount    # 売上を累計
        print(f"  注文 {order_no}) {name} {qty}杯 -> {amount}ウォン (累計 {day_total}ウォン)")

    print(f"  -> 注文が300件になってもコードはそのままです。これが「繰り返し」の力です。")

    # ---------------------------------------------------------
    # [4] 今日の結論
    # ---------------------------------------------------------
    print("\n[4] まとめ")
    print("  プログラム = データ(価格、数量、名前...) + 手順(計算、判断、出力...)")
    print("  そして、すべての手順は次の3つの組み合わせです:")
    print("    1. 順次 — 上から下へ")
    print("    2. 分岐 — 条件によって違う道へ")
    print("    3. 繰り返し — 同じ仕事を何度も")
    print("  次のレベルから、この3つを一つずつじっくり学びます。")


if __name__ == "__main__":
    main()
