"""프로그래밍이란 무엇인가 — 순차·분기·반복 데모.

카페의 '아메리카노 주문 처리' 업무 매뉴얼을 파이썬 절차로 옮겨 봅니다.
[1] 순차: 위에서 아래로 차례대로 실행
[2] 분기: 조건(포인트 회원 여부)에 따라 다른 길
[3] 반복: 여러 주문을 같은 절차로 처리
모든 프로그램은 이 세 가지의 조합이라는 것을 눈으로 확인합니다.
"""


def main():
    print("=" * 52)
    print(" 프로그래밍이란? — 아메리카노 주문 처리 절차 데모")
    print("=" * 52)

    # ---------------------------------------------------------
    # [1] 순차(sequence): 코드는 위에서 아래로 차례대로 실행된다
    # ---------------------------------------------------------
    print("\n[1] 순차 — 주문 1건을 절차대로 처리합니다")

    customer = "김주임"        # 데이터: 손님 이름
    cup_price = 4500           # 데이터: 아메리카노 한 잔 가격(원)
    quantity = 2               # 데이터: 주문 수량

    print(f"  단계 1) 주문 접수: {customer} 님, 아메리카노 {quantity}잔")

    total = cup_price * quantity          # 절차: 금액 계산
    print(f"  단계 2) 금액 계산: {cup_price}원 x {quantity}잔 = {total}원")

    print(f"  단계 3) 영수증 출력: 총 {total}원 결제 완료")
    print("  -> 위 세 줄은 반드시 이 순서로 실행됩니다. 이것이 '순차'입니다.")

    # ---------------------------------------------------------
    # [2] 분기(branch): 조건에 따라 다른 길을 간다
    # ---------------------------------------------------------
    print("\n[2] 분기 — 포인트 회원 여부에 따라 절차가 갈라집니다")

    is_member = True           # 데이터: 포인트 회원인가? (True/False 로 바꿔 보세요)

    if is_member:              # <-- 여기가 갈림길입니다
        point = int(total * 0.05)   # 회원이면 5% 적립
        print(f"  회원 확인 O -> 포인트 {point}점 적립")
    else:
        print("  회원 확인 X -> 적립 없이 바로 다음 단계로")
    print("  -> '만약 ~라면'으로 갈라지는 것이 '분기'입니다.")

    # ---------------------------------------------------------
    # [3] 반복(loop): 같은 절차를 여러 데이터에 적용한다
    # ---------------------------------------------------------
    print("\n[3] 반복 — 대기 중인 주문 3건을 같은 절차로 처리합니다")

    # (이름, 수량) 묶음이 3개 든 주문 대기 목록
    waiting_orders = [
        ("이과장", 1),
        ("박대리", 3),
        ("최부장", 2),
    ]

    order_no = 0
    day_total = 0
    for name, qty in waiting_orders:      # <-- 목록의 각 주문마다 아래 절차를 반복
        order_no = order_no + 1
        amount = cup_price * qty
        day_total = day_total + amount    # 매출 누적
        print(f"  주문 {order_no}) {name} 님 {qty}잔 -> {amount}원 (누적 {day_total}원)")

    print(f"  -> 주문이 300건이어도 코드는 그대로입니다. 이것이 '반복'의 힘입니다.")

    # ---------------------------------------------------------
    # [4] 오늘의 결론
    # ---------------------------------------------------------
    print("\n[4] 요약")
    print("  프로그램 = 데이터(가격, 수량, 이름...) + 절차(계산, 판단, 출력...)")
    print("  그리고 모든 절차는 다음 세 가지의 조합입니다:")
    print("    1. 순차 — 위에서 아래로")
    print("    2. 분기 — 조건에 따라 다른 길로")
    print("    3. 반복 — 같은 일을 여러 번")
    print("  다음 레벨부터 이 셋을 하나씩 제대로 배웁니다.")


if __name__ == "__main__":
    main()
