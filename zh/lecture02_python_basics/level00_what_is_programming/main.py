"""编程到底是什么 — 顺序·分支·循环演示。

我们把咖啡店"美式咖啡点单处理"这份业务手册翻译成 Python 流程。
[1] 顺序: 从上到下依次执行
[2] 分支: 根据条件 (是否是积分会员) 走不同的路
[3] 循环: 用同一套流程处理多笔订单
亲眼确认一件事: 所有程序都是这三者的组合。
"""


def main():
    print("=" * 52)
    print(" 编程是什么? — 美式咖啡点单处理流程演示")
    print("=" * 52)

    # ---------------------------------------------------------
    # [1] 顺序(sequence): 代码从上到下依次执行
    # ---------------------------------------------------------
    print("\n[1] 顺序 — 按流程处理 1 笔订单")

    customer = "王主管"        # 数据: 顾客姓名
    cup_price = 4500           # 数据: 美式咖啡单杯价格 (韩元)
    quantity = 2               # 数据: 下单数量

    print(f"  步骤 1) 接单: {customer}，美式咖啡 {quantity} 杯")

    total = cup_price * quantity          # 流程: 计算金额
    print(f"  步骤 2) 计算金额: {cup_price}韩元 x {quantity}杯 = {total}韩元")

    print(f"  步骤 3) 打印小票: 共 {total}韩元，支付完成")
    print("  -> 上面三步一定按这个顺序执行。这就是'顺序'。")

    # ---------------------------------------------------------
    # [2] 分支(branch): 根据条件走不同的路
    # ---------------------------------------------------------
    print("\n[2] 分支 — 流程按是否为积分会员分岔")

    is_member = True           # 数据: 是积分会员吗? (试着改成 True/False)

    if is_member:              # <-- 这里就是岔路口
        point = int(total * 0.05)   # 是会员就返 5% 积分
        print(f"  会员确认 O -> 累计积分 {point} 分")
    else:
        print("  会员确认 X -> 不返积分，直接进入下一步")
    print("  -> 用'如果……就……'分岔，这就是'分支'。")

    # ---------------------------------------------------------
    # [3] 循环(loop): 把同一套流程应用到多份数据上
    # ---------------------------------------------------------
    print("\n[3] 循环 — 用同一套流程处理排队中的 3 笔订单")

    # 装着 3 组 (姓名, 数量) 的待处理订单列表
    waiting_orders = [
        ("李经理", 1),
        ("张助理", 3),
        ("陈总监", 2),
    ]

    order_no = 0
    day_total = 0
    for name, qty in waiting_orders:      # <-- 对列表里的每笔订单重复下面的流程
        order_no = order_no + 1
        amount = cup_price * qty
        day_total = day_total + amount    # 累加营业额
        print(f"  订单 {order_no}) {name} {qty}杯 -> {amount}韩元 (累计 {day_total}韩元)")

    print(f"  -> 就算有 300 笔订单，代码还是这几行。这就是'循环'的威力。")

    # ---------------------------------------------------------
    # [4] 今天的结论
    # ---------------------------------------------------------
    print("\n[4] 小结")
    print("  程序 = 数据(价格、数量、姓名……) + 流程(计算、判断、输出……)")
    print("  而所有流程都是下面三者的组合:")
    print("    1. 顺序 — 从上到下")
    print("    2. 分支 — 按条件走不同的路")
    print("    3. 循环 — 同一件事做很多次")
    print("  从下一关开始，我们把这三样逐个学扎实。")


if __name__ == "__main__":
    main()
